// Helper to generate realistic candle bars for charts
export function generateCandlesForSymbol(symbol: string, count: number = 60, basePrice?: number): CandleData[] {
  const asset = INITIAL_ASSETS.find(a => a.symbol === symbol);
  let price = basePrice || (asset ? asset.price : 100);
  const volatility = price * 0.012; // 1.2% per bar
  
  const candles: CandleData[] = [];
  const now = new Date();
  
  // Start from past
  for (let i = count - 1; i >= 0; i--) {
    const time = new Date(now.getTime() - i * 15 * 60 * 1000);
    const timeStr = time.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
    
    const delta = (Math.random() - 0.48) * volatility;
    const open = Math.round((price - delta) * 100) / 100;
    const close = Math.round(price * 100) / 100;
    const high = Math.round((Math.max(open, close) + Math.random() * (volatility * 0.6)) * 100) / 100;
    const low = Math.round((Math.min(open, close) - Math.random() * (volatility * 0.6)) * 100) / 100;
    const volume = Math.round(10000 + Math.random() * 50000);
    
    candles.push({
      time: timeStr,
      open,
      high,
      low,
      close,
      volume,
    });
    
    price += (Math.random() - 0.48) * (volatility * 0.8);
  }
  
  return candles;
}
